"""Build a broad US stock universe with less survivorship bias.

The hand-written large-cap list only contains today's winners. This builder:
  1. lists every US-listed asset Alpaca knows, ACTIVE and INACTIVE (delisted),
  2. drops obvious non-common-stock (ETFs, funds, warrants, units, rights, SPACs, preferreds),
  3. pulls MONTHLY bars for all of them (cheap), and
  4. keeps every stock that ranked in the top `top_n` by traded value in at
     least `min_months` months of the period, with price >= min_price that month.

So a company that was liquid in 2020 and went bust in 2023 is included.
This reduces, but doesn't remove, survivorship bias: it depends on Alpaca
still holding data for delisted symbols, and reused tickers can be mixed up.
"""

from __future__ import annotations

import logging
import re
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

log = logging.getLogger("tradebot.universe")

EXCHANGES = {"NYSE", "NASDAQ", "AMEX"}
SYMBOL_OK = re.compile(r"^[A-Z]{1,5}$")
NAME_EXCLUDE = re.compile(
    r"\b(ETF|ETN|FUND|TRUST|WARRANTS?|UNITS?|RIGHTS?|ACQUISITION|PREFERRED|PFD|DEPOSITARY SHARES? REPRESENTING|"
    r"NOTES?|DEBENTURES?|INDEX|PROSHARES|ISHARES|SPDR|DIREXION|INVESCO|VANGUARD|LEVERAGED|INVERSE|2X|3X)\b",
    re.IGNORECASE,
)


def candidate_assets(assets) -> list[str]:
    """Filter Alpaca Asset objects (or dicts with the same fields) to likely common stocks."""
    out = []
    for a in assets:
        get = a.get if isinstance(a, dict) else lambda k, a=a: getattr(a, k, None)
        exchange = str(getattr(get("exchange"), "value", get("exchange")) or "")
        cls = str(getattr(get("asset_class"), "value", get("asset_class")) or "")
        symbol, name = get("symbol") or "", get("name") or ""
        if cls and cls != "us_equity":
            continue
        if exchange not in EXCHANGES or not SYMBOL_OK.match(symbol) or NAME_EXCLUDE.search(name):
            continue
        out.append(symbol)
    return sorted(set(out))


def select_liquid(monthly: pd.DataFrame, top_n: int, min_months: int, min_price: float) -> list[str]:
    """Symbols that were among the `top_n` most traded (by $ value) in >= min_months months."""
    if monthly.empty:
        return []
    m = monthly.assign(month=monthly["timestamp"].dt.strftime("%Y-%m"), dv=monthly["close"] * monthly["volume"])
    m = m[m["close"] >= min_price]
    m["rank"] = m.groupby("month")["dv"].rank(ascending=False, method="first")
    hits = m[m["rank"] <= top_n].groupby("symbol").size()
    return sorted(hits[hits >= min_months].index)


def write_universe(path: str | Path, symbols: list[str], note: str) -> None:
    lines = [
        "# Broad US universe generated by `tradebot build-universe`",
        f"# {note}",
        f"# generated {datetime.now(timezone.utc):%Y-%m-%d}, {len(symbols)} symbols",
        "",
    ]
    lines += [" ".join(symbols[i : i + 10]) for i in range(0, len(symbols), 10)]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n")


def build_us_universe(data, trading_client, years: int, top_n: int, min_months: int, min_price: float) -> list[str]:
    from datetime import timedelta

    from alpaca.trading.enums import AssetClass, AssetStatus
    from alpaca.trading.requests import GetAssetsRequest

    from tradebot.data.alpaca import MONTHLY

    # trading_client must be created with raw_data=True: alpaca-py's Asset model rejects
    # exchanges it doesn't know yet (e.g. TXSE, the Texas Stock Exchange), so we take dicts.
    assets = []
    for status in (AssetStatus.ACTIVE, AssetStatus.INACTIVE):
        got = trading_client.get_all_assets(GetAssetsRequest(status=status, asset_class=AssetClass.US_EQUITY))
        log.info("%d %s assets", len(got), status.value)
        assets += got
    candidates = candidate_assets(assets)
    log.info("%d candidate common stocks after filtering", len(candidates))
    end = datetime.now(timezone.utc)
    monthly = data.get_bars(candidates, end - timedelta(days=365 * years), end, MONTHLY)
    log.info("monthly bars for %d symbols", monthly["symbol"].nunique() if not monthly.empty else 0)
    return select_liquid(monthly, top_n, min_months, min_price)
