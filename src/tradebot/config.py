class Settings(BaseModel):
    mode: Literal["paper", "live"] = "paper"
    bar_minutes: int = 5
    db_path: str = "data/tradebot.sqlite"
    markets: dict[Market, MarketConfig] = Field(default_factory=dict)
    strategy: StrategyConfig = Field(default_factory=StrategyConfig)
    scanner: ScannerConfig = Field(default_factory=ScannerConfig)
    risk: RiskConfig = Field(default_factory=RiskConfig)
    daily: DailyConfig = Field(default_factory=DailyConfig)
    alpaca: AlpacaConfig = Field(default_factory=AlpacaConfig)
    ibkr: IBKRConfig = Field(default_factory=IBKRConfig)

    def enabled_markets(self) -> list[Market]:
        return [m for m, c in self.markets.items() if c.enabled]

    def universe(self, market: Market, timeframe: str = "intraday", which: str = "default") -> list[str]:
        mcfg = self.markets[market]
        if which == "broad":
            if not mcfg.broad_universe_file:
                raise ValueError(f"No broad_universe_file configured for {market.value}")
            return read_universe(mcfg.broad_universe_file)
        if timeframe == "daily" and mcfg.daily_universe_file:
            return read_universe(mcfg.daily_universe_file)
        return list(mcfg.universe)


def read_universe(path: str | Path) -> list[str]:
    p = Path(path)
    if not p.is_absolute() and not p.exists():
        p = REPO_ROOT / p
    symbols = []
    for line in p.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            symbols.extend(line.split())
    return list(dict.fromkeys(symbols))  # dedupe, keep order


def load_dotenv(path: str | Path = ".env") -> None:
    """Minimal .env loader: KEY=VALUE lines; existing env vars win."""
    p = Path(path)
    if not p.exists():
        return
    for line in p.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def load_settings(path: str | Path | None = None) -> Settings:
    load_dotenv()
    cfg_path = Path(path) if path else DEFAULT_CONFIG
    with open(cfg_path) as fh:
        raw = yaml.safe_load(fh) or {}
    return Settings.model_validate(raw)


def live_trading_confirmed() -> bool:
    return os.environ.get(LIVE_CONFIRM_ENV) == LIVE_CONFIRM_VALUE


def assert_live_allowed(settings: Settings) -> None:
    """Raise unless live trading has been explicitly enabled twice over."""
    if settings.mode != "live":
        raise PermissionError("Config mode is not 'live'.")
    if not live_trading_confirmed():
        raise PermissionError(
            f"Live trading needs {LIVE_CONFIRM_ENV}={LIVE_CONFIRM_VALUE} in the environment."
        )
