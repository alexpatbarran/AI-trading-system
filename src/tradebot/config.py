from tradebot.domain import Market

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = REPO_ROOT / "config" / "default.yaml"
LIVE_CONFIRM_ENV = "TRADEBOT_CONFIRM_LIVE"
LIVE_CONFIRM_VALUE = "I_UNDERSTAND_THE_RISKS"


